# ----------------------------------------------------------------------------------------------------------------------
# helper to remove boundaries (set to NaN)
def nullify_bounds(arr, no_data=np.nan):
    arr[0, :] = no_data
    arr[-1, :] = no_data
    arr[:, 0] = no_data
    arr[:, -1] = no_data
    return arr
